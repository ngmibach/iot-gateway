"""Render Grafana custom.ini and base Prometheus/Loki datasource provisioning."""

from __future__ import annotations

from pathlib import Path


def render_grafana_ini(
    *,
    grafana_data: Path,
    logs_dir: Path,
    plugins_dir: Path,
    provisioning_dir: Path,
    cert_file: Path,
    cert_key: Path,
    admin_password: str,
    http_port: int = 9140,
) -> str:
    """Generate custom ``grafana.ini`` for localhost HTTPS (design §4)."""
    data = Path(grafana_data).as_posix()
    logs = Path(logs_dir).as_posix()
    plugins = Path(plugins_dir).as_posix()
    provisioning = Path(provisioning_dir).as_posix()
    cert = Path(cert_file).as_posix()
    key = Path(cert_key).as_posix()
    port = int(http_port)
    # Password may contain special chars from token_urlsafe; write raw (ini string).
    return (
        "# Generated by native telemetry — do not edit by hand.\n"
        "[paths]\n"
        f"data = {data}\n"
        f"logs = {logs}\n"
        f"plugins = {plugins}\n"
        f"provisioning = {provisioning}\n"
        "\n"
        "[server]\n"
        "protocol = https\n"
        "http_addr = 127.0.0.1\n"
        f"http_port = {port}\n"
        "domain = localhost\n"
        f"root_url = https://127.0.0.1:{port}/\n"
        f"cert_file = {cert}\n"
        f"cert_key = {key}\n"
        "certs_watch_interval = 5m\n"
        'min_tls_version = "TLS1.2"\n'
        "enforce_domain = false\n"
        "\n"
        "[security]\n"
        "admin_user = admin\n"
        f"admin_password = {admin_password}\n"
        "disable_gravatar = true\n"
        "cookie_secure = true\n"
        "cookie_samesite = strict\n"
        "\n"
        "[users]\n"
        "allow_sign_up = false\n"
        "allow_org_create = false\n"
        "\n"
        "[auth.anonymous]\n"
        "enabled = true\n"
        "org_name = Main Org.\n"
        "org_role = Admin\n"
        "hide_version = false\n"
        "\n"
        "[auth.basic]\n"
        "enabled = false\n"
        "\n"
        "[analytics]\n"
        "reporting_enabled = false\n"
        "check_for_updates = false\n"
        "\n"
        "[news]\n"
        "news_feed_enabled = false\n"
    )


def render_datasources_yaml() -> str:
    """Prometheus + Loki datasources only (Kafka is PR 2b)."""
    return (
        "apiVersion: 1\n"
        "datasources:\n"
        "  - name: Prometheus\n"
        "    type: prometheus\n"
        "    access: proxy\n"
        "    uid: iotgw-prometheus\n"
        "    url: http://127.0.0.1:9090\n"
        "    isDefault: true\n"
        "    editable: true\n"
        "  - name: Loki\n"
        "    type: loki\n"
        "    access: proxy\n"
        "    uid: iotgw-loki\n"
        "    url: http://127.0.0.1:3100\n"
        "    editable: true\n"
    )


def write_grafana_base_config(
    config_dir: Path,
    *,
    grafana_data: Path,
    logs_dir: Path,
    plugins_dir: Path,
    cert_file: Path,
    cert_key: Path,
    admin_password: str,
    http_port: int = 9140,
) -> dict[str, Path]:
    """Write ``grafana.ini`` and Prom/Loki ``datasources.yaml`` under ``config_dir``."""
    config_dir = Path(config_dir)
    provisioning = config_dir / "provisioning"
    ds_dir = provisioning / "datasources"
    ds_dir.mkdir(parents=True, exist_ok=True)

    ini_path = config_dir / "grafana.ini"
    ds_path = ds_dir / "datasources.yaml"

    ini_path.write_text(
        render_grafana_ini(
            grafana_data=grafana_data,
            logs_dir=logs_dir,
            plugins_dir=plugins_dir,
            provisioning_dir=provisioning,
            cert_file=cert_file,
            cert_key=cert_key,
            admin_password=admin_password,
            http_port=http_port,
        ),
        encoding="utf-8",
    )
    ds_path.write_text(render_datasources_yaml(), encoding="utf-8")
    return {"grafana_ini": ini_path, "datasources_yaml": ds_path}
