"""Render Grafana custom.ini and Prometheus/Loki/Kafka datasource provisioning."""

from __future__ import annotations

import hashlib
import ipaddress
import re
import ssl
from pathlib import Path
from typing import Any
from urllib.error import HTTPError, URLError
from urllib.request import (
    HTTPRedirectHandler,
    HTTPSHandler,
    Request,
    build_opener,
)

_KAFKA_PLUGIN_ID = "hamedkarbasi93-kafka-datasource"
_UID_SAFE = re.compile(r"[^a-zA-Z0-9-]+")
_HOSTNAME_RE = re.compile(
    r"^(?=.{1,253}$)(?!-)[A-Za-z0-9-]{1,63}(?<!-)"
    r"(\.(?!-)[A-Za-z0-9-]{1,63}(?<!-))*$"
)
_ALLOWED_GRAFANA_ORIGINS = frozenset(
    {
        "https://127.0.0.1:9140",
        "https://localhost:9140",
    }
)


def _sanitize_uid_part(value: str) -> str:
    """Return Grafana uid segment; append hash when sanitization alters the id."""
    raw = (value or "").strip()
    cleaned = _UID_SAFE.sub("-", raw).strip("-") or "gateway"
    if cleaned != raw:
        suffix = hashlib.sha256(raw.encode("utf-8")).hexdigest()[:8]
        return f"{cleaned}-{suffix}"
    return cleaned


def _yaml_double_quoted(value: str) -> str:
    """Emit a YAML double-quoted scalar (no PyYAML dependency)."""
    escaped = (
        value.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\r", "\\r")
        .replace("\t", "\\t")
    )
    return f'"{escaped}"'


def _validate_bootstrap_host(host: str) -> str | None:
    """Accept a single IP or DNS hostname; reject quote/control injection."""
    h = (host or "").strip()
    if not h or len(h) > 253:
        return None
    if any(ord(c) < 32 or c in ' "\'\\' for c in h):
        return None
    try:
        return str(ipaddress.ip_address(h))
    except ValueError:
        pass
    if _HOSTNAME_RE.fullmatch(h):
        return h
    return None


def _validate_gateway_label(gid: str) -> str | None:
    """Gateway id safe for a quoted YAML display name."""
    g = (gid or "").strip()
    if not g or len(g) > 128:
        return None
    if any(ord(c) < 32 for c in g):
        return None
    return g


def render_grafana_ini(
    *,
    grafana_data: Path,
    logs_dir: Path,
    plugins_dir: Path,
    provisioning_dir: Path,
    cert_file: Path,
    cert_key: Path,
    admin_password: str,
    http_port: int = 9140,
) -> str:
    """Generate custom ``grafana.ini`` for localhost HTTPS (design §4)."""
    data = Path(grafana_data).as_posix()
    logs = Path(logs_dir).as_posix()
    plugins = Path(plugins_dir).as_posix()
    provisioning = Path(provisioning_dir).as_posix()
    cert = Path(cert_file).as_posix()
    key = Path(cert_key).as_posix()
    port = int(http_port)
    # Password may contain special chars from token_urlsafe; write raw (ini string).
    return (
        "# Generated by native telemetry — do not edit by hand.\n"
        "[paths]\n"
        f"data = {data}\n"
        f"logs = {logs}\n"
        f"plugins = {plugins}\n"
        f"provisioning = {provisioning}\n"
        "\n"
        "[server]\n"
        "protocol = https\n"
        "http_addr = 127.0.0.1\n"
        f"http_port = {port}\n"
        "domain = localhost\n"
        f"root_url = https://127.0.0.1:{port}/\n"
        f"cert_file = {cert}\n"
        f"cert_key = {key}\n"
        "certs_watch_interval = 5m\n"
        'min_tls_version = "TLS1.2"\n'
        "enforce_domain = false\n"
        "\n"
        "[security]\n"
        "admin_user = admin\n"
        f"admin_password = {admin_password}\n"
        "disable_gravatar = true\n"
        "cookie_secure = true\n"
        "cookie_samesite = strict\n"
        "\n"
        "[users]\n"
        "allow_sign_up = false\n"
        "allow_org_create = false\n"
        "\n"
        "[auth.anonymous]\n"
        "enabled = true\n"
        "org_name = Main Org.\n"
        "org_role = Admin\n"
        "hide_version = false\n"
        "\n"
        "[auth.basic]\n"
        "enabled = false\n"
        "\n"
        "[plugins]\n"
        f"allow_loading_unsigned_plugins = {_KAFKA_PLUGIN_ID}\n"
        "\n"
        "[analytics]\n"
        "reporting_enabled = false\n"
        "check_for_updates = false\n"
        "\n"
        "[news]\n"
        "news_feed_enabled = false\n"
    )


def render_datasources_yaml(*, gateways: list[dict[str, Any]] | None = None) -> str:
    """Prometheus + Loki, plus one Kafka datasource per gateway with a host."""
    parts = [
        "apiVersion: 1\n"
        "datasources:\n"
        "  - name: Prometheus\n"
        "    type: prometheus\n"
        "    access: proxy\n"
        "    uid: iotgw-prometheus\n"
        "    url: http://127.0.0.1:9090\n"
        "    isDefault: true\n"
        "    editable: true\n"
        "  - name: Loki\n"
        "    type: loki\n"
        "    access: proxy\n"
        "    uid: iotgw-loki\n"
        "    url: http://127.0.0.1:3100\n"
        "    editable: true\n"
    ]
    for gw in gateways or []:
        if not isinstance(gw, dict):
            continue
        # Registry rows use ``id``; accept ``gateway_id`` as a thin alias.
        gid = _validate_gateway_label(
            str(gw.get("id") or gw.get("gateway_id") or "")
        )
        host = _validate_bootstrap_host(str(gw.get("host") or ""))
        if not gid or not host:
            continue
        uid = f"iotgw-kafka-{_sanitize_uid_part(gid)}"
        name = _yaml_double_quoted(f"Kafka ({gid})")
        bootstrap = _yaml_double_quoted(f"{host}:9092")
        parts.append(
            f"  - name: {name}\n"
            f"    type: {_KAFKA_PLUGIN_ID}\n"
            "    access: proxy\n"
            f"    uid: {uid}\n"
            "    editable: true\n"
            "    jsonData:\n"
            f"      bootstrapServers: {bootstrap}\n"
            '      securityProtocol: "PLAINTEXT"\n'
        )
    return "".join(parts)


def write_grafana_base_config(
    config_dir: Path,
    *,
    grafana_data: Path,
    logs_dir: Path,
    plugins_dir: Path,
    cert_file: Path,
    cert_key: Path,
    admin_password: str,
    http_port: int = 9140,
    gateways: list[dict[str, Any]] | None = None,
) -> dict[str, Path]:
    """Write ``grafana.ini`` and Prom/Loki/Kafka ``datasources.yaml`` under ``config_dir``."""
    config_dir = Path(config_dir)
    provisioning = config_dir / "provisioning"
    ds_dir = provisioning / "datasources"
    ds_dir.mkdir(parents=True, exist_ok=True)

    ini_path = config_dir / "grafana.ini"
    ds_path = ds_dir / "datasources.yaml"

    ini_path.write_text(
        render_grafana_ini(
            grafana_data=grafana_data,
            logs_dir=logs_dir,
            plugins_dir=plugins_dir,
            provisioning_dir=provisioning,
            cert_file=cert_file,
            cert_key=cert_key,
            admin_password=admin_password,
            http_port=http_port,
        ),
        encoding="utf-8",
    )
    ds_path.write_text(
        render_datasources_yaml(gateways=gateways), encoding="utf-8"
    )
    return {"grafana_ini": ini_path, "datasources_yaml": ds_path}


def _allowlisted_grafana_origin(grafana_url: str) -> str | None:
    origin = (grafana_url or "").strip().rstrip("/")
    for allowed in _ALLOWED_GRAFANA_ORIGINS:
        if origin.lower() == allowed.lower():
            return allowed
    return None


class _DenyRedirect(HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):  # noqa: ANN001
        raise URLError(f"redirect denied off allowlist: {newurl}")


def _grafana_opener():
    ctx = ssl._create_unverified_context()
    return build_opener(HTTPSHandler(context=ctx), _DenyRedirect())


def _grafana_https_healthy(grafana_url: str, *, timeout: float = 2.0) -> bool:
    origin = _allowlisted_grafana_origin(grafana_url)
    if origin is None:
        return False
    url = origin + "/api/health"
    try:
        with _grafana_opener().open(url, timeout=timeout) as resp:  # noqa: S310
            return 200 <= getattr(resp, "status", 200) < 300
    except (URLError, HTTPError, OSError, TimeoutError):
        return False


def _reload_grafana_datasources(grafana_url: str, *, timeout: float = 5.0) -> bool:
    origin = _allowlisted_grafana_origin(grafana_url)
    if origin is None:
        return False
    url = origin + "/api/admin/provisioning/datasources/reload"
    req = Request(url, data=b"", method="POST")
    try:
        with _grafana_opener().open(req, timeout=timeout) as resp:  # noqa: S310
            return 200 <= getattr(resp, "status", 200) < 300
    except (URLError, HTTPError, OSError, TimeoutError):
        return False


def sync_grafana_datasources(
    *,
    config_dir: Path,
    registry_path: Path | None = None,
    grafana_url: str = "https://127.0.0.1:9140",
    reload: bool = True,
) -> dict[str, Any]:
    """Rewrite provisioned datasources from the local registry; optional Grafana reload.

    File write always happens. Reload is best-effort when Grafana is up
    (anonymous Admin; unverified localhost TLS). Does not raise if Grafana is down.
    """
    from registry.registry import Registry  # type: ignore[import-not-found]

    config_dir = Path(config_dir)
    ds_dir = config_dir / "provisioning" / "datasources"
    ds_dir.mkdir(parents=True, exist_ok=True)
    ds_path = ds_dir / "datasources.yaml"

    if registry_path is None:
        from .native import default_native_root

        # <data>/telemetry → <data>/registry.sqlite
        registry_path = default_native_root().parent / "registry.sqlite"

    gateways: list[dict[str, Any]] = []
    reg_path = Path(registry_path)
    if reg_path.is_file():
        reg = Registry(str(reg_path))
        try:
            gateways = reg.list_gateways()
        finally:
            reg.close()

    ds_path.write_text(render_datasources_yaml(gateways=gateways), encoding="utf-8")

    reloaded = False
    if reload:
        if _grafana_https_healthy(grafana_url):
            reloaded = _reload_grafana_datasources(grafana_url)

    return {
        "gateways": len(gateways),
        "reloaded": reloaded,
        "path": str(ds_path),
    }
